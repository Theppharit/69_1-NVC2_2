# === รับค่าสินค้า รายการที่ 1 ===
print("--- สินค้ารายการที่ 1 ---")
name1 = input("rd: ")
price1 = int(input("กรอกราคาต่อชิ้น (บาท): "))
qty1 = int(input("กรอกจำนวนที่ขาย: "))
total1 = price1 * qty1

# === รับค่าสินค้า รายการที่ 2 ===
print("\n--- สินค้ารายการที่ 2 ---")
name2 = input("pb: ")
price2 = int(input("กรอกราคาต่อชิ้น (บาท): "))
qty2 = int(input("กรอกจำนวนที่ขาย: "))
total2 = price2 * qty2

# === แสดงผลลัพธ์ ===

print(f"รายการที่ 1: {name1} | ราคาชิ้นละ {price1} บาท | ขายได้ {qty1} ชิ้น | ยอดรวม {total1} บาท")
print(f"รายการที่ 2: {name2} | ราคาชิ้นละ {price2} บาท | ขายได้ {qty2} ชิ้น | ยอดรวม {total2} บาท")
print(f"ยอดขายรวมทั้งหมด: {total1 + total2} บาท")